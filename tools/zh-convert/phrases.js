window.ZhPhrasesT2S = Object.fromEntries(Object.entries(window.ZhPhrases).map(([a, b]) => [b, a]));
window.convertWithPhrases = function (text, phrases, chars) {
  const max = Object.keys(phrases).reduce((n, key) => Math.max(n, key.length), 1);
  let out = "";
  let i = 0;
  while (i < text.length) {
    let hit = "";
    let used = 0;
    for (let len = Math.min(max, text.length - i); len >= 2; len -= 1) {
      const slice = text.slice(i, i + len);
      if (phrases[slice]) { hit = phrases[slice]; used = len; break; }
    }
    if (hit) { out += hit; i += used; }
    else { const ch = text[i]; out += (chars && chars[ch]) || ch; i += 1; }
  }
  return out;
};
